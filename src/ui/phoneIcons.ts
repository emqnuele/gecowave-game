// lo specchio di avanti: stesso disegno, verso opposto
GLYPHS.indietro = GLYPHS.avanti.map((row) => [...row].reverse().join(''));

/** il glifo come svg a pixel netti: scala intera, niente sfumature ai bordi */
export function pixelIcon(id: string): string {
    const rows = GLYPHS[id];
    if (!rows) return '';
    let rects = '';
    rows.forEach((row, y) => {
        for (let x = 0; x < row.length; x++) {
            const c = row[x];
            if (c === '.') continue;
            // le corse orizzontali diventano un rettangolo solo
            let w = 1;
            while (row[x + w] === c) w++;
            rects += `<rect x="${x}" y="${y}" width="${w}" height="1"${c === '+' ? ' opacity=".55"' : ''}/>`;
            x += w - 1;
        }
    });
    return `<svg viewBox="0 0 12 12" shape-rendering="crispEdges" fill="currentColor" aria-hidden="true">${rects}</svg>`;
}
